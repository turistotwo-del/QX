"""Single source of truth for QX Workspace version / installer identity.

The update is a DEVELOPMENT build until it has been installed and tested on
Windows.  Keep this flag visible rather than claiming production readiness.
"""
from __future__ import annotations

APP_VERSION = '4.0.41'
BUILD_CHANNEL = 'development'
RELEASE_LABEL = f'{APP_VERSION} ({BUILD_CHANNEL})'
SETUP_BASENAME = 'QX_Setup_' + APP_VERSION.replace('.', '_') + '_DEV'
WINDOWS_PRODUCT_VERSION = APP_VERSION + '.0'


def inno_defines() -> str:
    """Generate valid Inno preprocessor directives from validated constants."""
    import re
    if not re.fullmatch(r'\d+\.\d+\.\d+', APP_VERSION):
        raise ValueError('Invalid APP_VERSION')
    if not re.fullmatch('[A-Za-z0-9_.-]+', SETUP_BASENAME):
        raise ValueError('Invalid installer file name')
    return ('; Generated by windows_build/release_metadata.py. Do not edit manually.\n'
            f'#define QXAppVersion "{APP_VERSION}-{BUILD_CHANNEL}"\n'
            f'#define QXProductVersion "{WINDOWS_PRODUCT_VERSION}"\n'
            f'#define QXOutputBase "{SETUP_BASENAME}"\n')
